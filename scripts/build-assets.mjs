// Generated delivery asset only. Edit the registered source stylesheets, never podview.css.
import {readFile,writeFile} from 'node:fs/promises';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../dist/',import.meta.url));
export const stylesheetSources=['ui/components.css','widget-view.css','ui/library/library.css','frame-layout.css','widget-redesign.css','timer-notice.css','live-music.css'];
export function composeStyles(sources,readSource,readAsset=()=>null){
 const sections=sources.map(source=>{
  const css=readSource(source);
  if(/@import\b/i.test(css))throw Error(`Unexpected CSS import in ${source}; add its owner to the ordered source list.`);
  const rebased=css.replace(/url\(\s*(['"]?)([^)'"\s]+)\1\s*\)/g,(all,quote,url)=>{
   if(/^(?:[a-z][a-z\d+.-]*:|\/|#)/i.test(url))return all;
   const rebased=path.posix.normalize(path.posix.join(path.posix.dirname(source),url));
   // Inline only small, exact bundled icon files. External/query URLs and larger
   // images retain their existing loading path. Base64 preserves original bytes.
   if(/^assets\/icons\/[a-z0-9-]+\.svg$/.test(rebased)){
    const asset=readAsset(rebased);
    if(asset&&asset.length<=4096)return `url("data:image/svg+xml;base64,${Buffer.from(asset).toString('base64')}")`;
   }
   return `url(${quote}${rebased}${quote})`;
  });
  return {source,sha256:createHash('sha256').update(css).digest('hex'),css:rebased};
 });
 return '/* GENERATED by scripts/build-assets.mjs. Canonical sources listed below; do not edit. */\n'+sections.map(section=>`/* Source: ${section.source} · SHA256 ${section.sha256} */\n${section.css}`).join('\n');
}
export async function buildStyles(){
 const files=new Map(await Promise.all(stylesheetSources.map(async source=>[source,await readFile(path.join(root,source),'utf8')])));
 const css=composeStyles(stylesheetSources,source=>files.get(source),source=>readFileSync(path.join(root,source)));
 const destination=path.join(root,'podview.css');
 let previous;try{previous=await readFile(destination,'utf8');}catch{}
 if(previous!==css)await writeFile(destination,css);
 return {file:'podview.css',sources:stylesheetSources.length,inlinedIconReferences:(css.match(/data:image\/svg\+xml;base64,/g)||[]).length,bytes:Buffer.byteLength(css),sha256:createHash('sha256').update(css).digest('hex')};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await buildStyles()));
