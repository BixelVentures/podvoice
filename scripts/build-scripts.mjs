// Build-only delivery bundling. Browser development retains the canonical ESM sources.
// Minify delivery bytes, retaining callable names and all component registration side effects.
import {buildSync,version} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const projectRoot=fileURLToPath(new URL('../',import.meta.url));
export const scriptBundles=[{file:'dist/podview.bundle.js',html:'dist/index.html',sources:['ui/stage.js','ingress-kiosk.js','widget-view.js']},{file:'dist/library.bundle.js',html:'dist/library.html',sources:['library.js']}];
// Locked npm packages resolve from this checkout's node_modules, also when root is a scratch copy of the product.
const vendorPackage=input=>
 /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\/(?!.*\/node_modules\/)/.exec(input)?.[1];
export function composeScriptBundle(root,bundle){
 root=fs.realpathSync(root);
 if(version!=='0.28.2')throw Error(`Expected pinned esbuild 0.28.2; got ${version}`);
 const base=path.dirname(bundle.html);
 const config=fs.readFileSync(path.join(root,'podvoice/config.yaml'),'utf8');
 const declarations=config.match(/^version:[^\r\n]*/gm)||[];
 // The publisher also reads the quoted top-level add-on version.
 const build=declarations.length===1&&/^version: "(\d+\.\d+\.\d+)"$/.exec(declarations[0])?.[1];
 if(!build)throw Error('Missing or invalid PodView build version in podvoice/config.yaml');
 const result=buildSync({
  define:{__PODVIEW_BUILD__:JSON.stringify(build)},
  absWorkingDir:root,
  nodePaths:[path.join(projectRoot,'node_modules')],
  stdin:{
   contents:bundle.sources.map(source=>`import ${JSON.stringify('./'+source)};`).join('\n'),
   resolveDir:path.join(root,base),
   sourcefile:'delivery-entry.js',
  },
  bundle:true,
  format:'esm',
  platform:'browser',
  target:'esnext',
  write:false,
  metafile:true,
  minify:true,
  treeShaking:true,
  keepNames:true,
  charset:'utf8',
  legalComments:'inline',
  logLevel:'silent',
 });
 const inputs=Object.keys(result.metafile.inputs).filter(input=>input!==path.posix.join(base,'delivery-entry.js')).sort();
 const own=inputs.filter(input=>!vendorPackage(input));
 const packages=[...new Set(inputs.map(vendorPackage).filter(Boolean))].sort();
 for(const input of own){
  if(!input.startsWith('dist/')||input.includes('node_modules'))throw Error(`Unexpected bundled dependency: ${input}`);
 }
 const pins=own.map(input=>
  `${input} ${createHash('sha256').update(fs.readFileSync(path.join(root,input))).digest('hex')}`);
 // Third-party code comes only from runtime dependencies locked in package-lock.json (Motion and its own packages),
 // pinned by name, version, license and the registry's integrity hash.
 const lock=packages.length
  ?JSON.parse(fs.readFileSync(path.join(projectRoot,'package-lock.json'),'utf8')).packages:{};
 for(const name of packages){
  const entry=lock[`node_modules/${name}`];
  if(!entry?.version||!entry.integrity||entry.dev)throw Error(`Unexpected bundled dependency: node_modules/${name}`);
  pins.push(`npm:${name}@${entry.version} ${entry.license||'UNLICENSED'} ${entry.integrity}`);
 }
 return `/* GENERATED by scripts/build-scripts.mjs · esbuild ${version}. Do not edit.\n${pins.join('\n')}\n*/\n${result.outputFiles[0].text}`;
}
export function buildScripts(){return scriptBundles.map(bundle=>{const text=composeScriptBundle(projectRoot,bundle),target=path.join(projectRoot,bundle.file);let prior;try{prior=fs.readFileSync(target,'utf8');}catch{}if(prior!==text)fs.writeFileSync(target,text);return {file:bundle.file,bytes:Buffer.byteLength(text),sha256:createHash('sha256').update(text).digest('hex')};});}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(buildScripts()));
