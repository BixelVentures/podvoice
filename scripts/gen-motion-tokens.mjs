#!/usr/bin/env node
// Writes the motion tokens (docs/MOTION.md §2) as CSS custom properties into podview/src/styles/motion-tokens.css
// from the values in podview/src/lib/motion/tokens.ts (Node runs the TypeScript directly).
// Run after changing DUR, EASE or SPRING: node scripts/gen-motion-tokens.mjs
// podview/src/lib/motion/tokens.test.ts fails when the CSS and tokens.ts disagree.
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DUR, EASE, SPRING, SPRING_BEZIER, springCurve} from '../podview/src/lib/motion/tokens.ts';

export const TOKENS_CSS = fileURLToPath(new URL('../podview/src/styles/motion-tokens.css', import.meta.url));
// flick is only used by JS springs after a gesture, so it has no CSS token.
const CSS_SPRINGS = ['quick', 'smooth', 'snappy'];

// One curve per bounce: the shape depends only on bounce, and duration only scales it. CSS gets the cubic-bezier fitted
// to the spring (SPRING_BEZIER in tokens.ts), never linear(): WebKit with Core Animation (the iPad) never accelerates a
// linear() easing, so every transition on it would run on the main thread.
export function springCurves() {
  const byBounce = new Map();
  const durations = {};
  for (const name of CSS_SPRINGS) {
    const spec = SPRING[name];
    const key = `--pv-spring-${Math.round(spec.bounce * 100)}`;
    if (!SPRING_BEZIER[key]) throw Error(`${name}: no fitted cubic-bezier for ${key}`);
    byBounce.set(key, SPRING_BEZIER[key]);
    durations[name] = {ms: springCurve(spec).ms, curve: key};
  }
  return {byBounce, durations};
}

export function motionTokenCss() {
  const {byBounce, durations} = springCurves();
  const lines = ['/* Generated by scripts/gen-motion-tokens.mjs from src/lib/motion/tokens.ts; do not edit. */', ':root {'];
  for (const [name, ms] of Object.entries(DUR)) lines.push(`  --pv-dur-${name}: ${ms}ms;`);
  for (const [name, value] of Object.entries(EASE)) lines.push(`  --pv-ease-${name}: ${value};`);
  for (const [name, value] of byBounce) lines.push(`  ${name}: ${value};`);
  for (const [name, {ms, curve}] of Object.entries(durations)) lines.push(`  --pv-spring-${name}: ${ms}ms var(${curve});`);
  lines.push('}', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = motionTokenCss();
  let current = '';
  try {
    current = readFileSync(TOKENS_CSS, 'utf8');
  } catch {}
  if (next !== current) writeFileSync(TOKENS_CSS, next);
  console.log(next === current ? 'motion tokens unchanged' : 'motion tokens written to motion-tokens.css');
}
