#!/usr/bin/env node
// Writes the motion tokens (docs/MOTION.md §2) as CSS custom properties into podview/src/styles/motion-tokens.css
// from the values in podview/src/lib/motion/tokens.ts (Node runs the TypeScript directly).
// Run after changing DUR or EASE: node scripts/gen-motion-tokens.mjs
// podview/src/lib/motion/tokens.test.ts fails when the CSS and tokens.ts disagree.
import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DUR, EASE} from '../podview/src/lib/motion/tokens.ts';

export const TOKENS_CSS = fileURLToPath(new URL('../podview/src/styles/motion-tokens.css', import.meta.url));

// Springs are motion/react's own (tokens.ts TRANSITION) and never reach CSS: CSS only times press feedback.
export function motionTokenCss() {
  const lines = [
    '/* Generated by scripts/gen-motion-tokens.mjs from src/lib/motion/tokens.ts; do not edit. Tailwind\'s theme:',
    '   ease-pv-out …; durations as duration-(--duration-pv-quick) (v4 has no duration theme). */',
    '@theme static {',
  ];
  for (const [name, ms] of Object.entries(DUR)) lines.push(`  --duration-pv-${name}: ${ms}ms;`);
  for (const [name, value] of Object.entries(EASE)) lines.push(`  --ease-pv-${name}: ${value};`);
  lines.push('}', '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = motionTokenCss();
  let current = '';
  try {
    current = readFileSync(TOKENS_CSS, 'utf8');
  } catch {}
  if (next !== current) writeFileSync(TOKENS_CSS, next);
  console.log(next === current ? 'motion tokens unchanged' : 'motion tokens written to motion-tokens.css');
}
