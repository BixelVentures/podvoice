#!/usr/bin/env node
// Writes the motion tokens (docs/MOTION.md §3.1) into ui-kit.css from the values in ui/motion.js.
// Run after changing DUR, EASE or SPRING: node scripts/gen-motion-tokens.mjs
// tests/podview/motion-tokens.test.mjs fails when the CSS and ui/motion.js disagree.
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DUR,EASE,SPRING,springCurve} from '../podview/ui/motion.js';

export const KIT_CSS=fileURLToPath(new URL('../podview/ui-kit.css',import.meta.url));
export const START='/* motion-tokens:start — generated by scripts/gen-motion-tokens.mjs from ui/motion.js; do not edit. */';
export const END='/* motion-tokens:end */';
// flick is only used by JS springs after a gesture, so it has no CSS token.
const CSS_SPRINGS=['quick','smooth','snappy'];

// One linear() per bounce: the curve shape depends only on bounce, and duration only scales it.
export function springCurves(){
 const byBounce=new Map(),durations={};
 for(const name of CSS_SPRINGS){
  const spec=SPRING[name],curve=springCurve(spec),key=`--pv-spring-${Math.round(spec.bounce*100)}`;
  const known=byBounce.get(key);
  if(known&&known!==curve.easing)throw Error(`${name} does not share the ${key} curve`);
  byBounce.set(key,curve.easing);durations[name]={ms:curve.ms,curve:key};
 }
 return {byBounce,durations};
}

// Wraps a linear() list after a comma so no generated line exceeds 120 characters.
function wrap(name,value){
 const lines=[],parts=value.split(', ');let line=` ${name}:`;
 parts.forEach((part,index)=>{
  const piece=part+(index<parts.length-1?',':';');
  if(line.length+piece.length+1>118){lines.push(line);line='  '+piece;}
  else line+=(line.endsWith(':')?'':' ')+piece;
 });
 lines.push(line);return lines.join('\n');
}

export function motionTokenBlock(){
 const {byBounce,durations}=springCurves();
 const lines=[START,':root{'];
 lines.push(' '+Object.entries(DUR).map(([name,ms])=>`--pv-dur-${name}:${ms}ms;`).join(''));
 lines.push(' '+Object.entries(EASE).map(([name,value])=>`--pv-ease-${name}:${value};`).join(''));
 for(const [name,value]of byBounce)lines.push(wrap(name,value));
 for(const [name,{ms,curve}]of Object.entries(durations))lines.push(` --pv-spring-${name}:${ms}ms var(${curve});`);
 lines.push('}',END);
 return lines.join('\n');
}

export function replaceBlock(css,block=motionTokenBlock()){
 const start=css.indexOf(START),end=css.indexOf(END);
 if(start<0||end<start)throw Error('ui-kit.css has no motion-tokens block');
 return css.slice(0,start)+block+css.slice(end+END.length);
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const css=readFileSync(KIT_CSS,'utf8'),next=replaceBlock(css);
 if(next!==css)writeFileSync(KIT_CSS,next);
 console.log(next===css?'motion tokens unchanged':'motion tokens written to ui-kit.css');
}
