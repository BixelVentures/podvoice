"""Explicit finite visual grants; immutable approval bindings, never legacy refill.

Only the trusted Supervisor option reaches this owner. The caller must obtain the
human approval before configuring it; an approval_ref is an audit identity, not
an approval generated by this module. Startup reserves the entire bundle. Unused
process allowance is lost on restart, exactly as for the existing visual owner.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path

import httpx

from .podview_enrichment import (
    MODEL,
    RequestAllowance,
    VisualSelector,
    _closed_json,
    _regular_read,
    configured_selector,
)

PURPOSE = "podview_visual_v1"
MAX_POLICY_BYTES = 1024
_FIELDS = {"purpose", "model", "max_requests", "grant_id", "approval_ref"}


def _policy(raw: str) -> tuple[dict, bytes] | None:
    try:
        if len(raw.encode("utf-8")) > MAX_POLICY_BYTES:
            return None
        value = _closed_json(raw)
        if (
            type(value) is not dict
            or set(value) != _FIELDS
            or value["purpose"] != PURPOSE
            or value["model"] != MODEL
            or type(value["max_requests"]) is not int
            or not 1 <= value["max_requests"] <= 20
            or type(value["grant_id"]) is not str
            or re.fullmatch(r"[a-f0-9]{32}", value["grant_id"]) is None
            or type(value["approval_ref"]) is not str
            or re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._:/-]{0,159}", value["approval_ref"]) is None
        ):
            return None
        return value, json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
    except (ValueError, TypeError, UnicodeError):
        return None


def _bind(path: Path, expected: bytes, directory_fd: int) -> bool:
    """Never replace or repair an existing, partial or differently bound identity."""
    try:
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    except FileExistsError:
        return _regular_read(path, MAX_POLICY_BYTES) == expected
    with os.fdopen(fd, "wb") as target:
        target.write(expected)
        target.flush()
        os.fsync(target.fileno())
    os.fsync(directory_fd)
    return True


def configured_visual_selector(
    client: httpx.AsyncClient,
    api_key: str,
    legacy_policy: str,
    legacy_path: Path,
    grant_policy: str = "",
) -> VisualSelector | None:
    """Empty grant preserves legacy admission; any supplied bad grant fails closed."""
    if not grant_policy:
        return configured_selector(client, api_key, legacy_policy, legacy_path)
    parsed = _policy(grant_policy)
    if not api_key or parsed is None:
        return None
    value, binding = parsed
    directory_fd: int | None = None
    try:
        directory_fd = os.open(legacy_path.parent, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        grant_id = value["grant_id"]
        approval_id = hashlib.sha256(value["approval_ref"].encode()).hexdigest()
        approval_path = legacy_path.parent / f"podview-visual-approval-{approval_id}.approval"
        binding_path = legacy_path.parent / f"podview-visual-grant-{grant_id}.approval"
        ledger_path = legacy_path.parent / f"podview-visual-grant-{grant_id}.json"
        # lexists includes broken symlinks. Missing identity files beside an
        # existing reservation are corruption, never a fresh grant to repair.
        identities = [os.path.lexists(path) for path in (approval_path, binding_path)]
        # A binding claims this grant's one startup, not a recoverable partial
        # balance. Every successful prepare prepays the entire maximum. Deny
        # every later startup even if reservation files disappeared or a valid
        # counter was rolled back. A crash before prepare loses the grant too.
        if any(identities):
            return None
        if not any(identities) and any(
            os.path.lexists(path)
            for path in (
                ledger_path,
                ledger_path.with_suffix(".initialized"),
                ledger_path.with_suffix(".lock"),
            )
        ):
            return None
        # Bind both identities before reserving. An interrupted/partial binding
        # conservatively blocks admission; it is never removed or repaired here.
        if not _bind(approval_path, binding, directory_fd) or not _bind(
            binding_path, binding, directory_fd
        ):
            return None
        allowance = RequestAllowance.prepare(ledger_path, value["max_requests"])
        if allowance is None:
            return None
        return VisualSelector(client, api_key, MODEL, allowance=allowance)
    except (OSError, ValueError, TypeError):
        return None
    finally:
        if directory_fd is not None:
            os.close(directory_fd)
